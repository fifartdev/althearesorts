/**
 * Generates src/lib/wp/schema-types.ts from wordpress/mu-plugins/althea-cms/schema.json.
 * Run after changing schema.json: npx tsx scripts/content/gen-types.ts
 */
import fs from 'node:fs'
import path from 'node:path'
import { fieldLocales, loadSchema, type Field } from './validate'

const ROOT = path.resolve(import.meta.dirname, '../..')
const OUT = path.join(ROOT, 'src/lib/wp/schema-types.ts')
const schema = loadSchema()

const pascal = (s: string) => s.replace(/(^|[-_])([a-z])/g, (_, __, c: string) => c.toUpperCase())

function valueType(f: Field): string {
  switch (f.type) {
    case 'image':
      return 'Media | null'
    case 'images':
      return 'Media[]'
    case 'bool':
      return 'boolean'
    case 'number':
      return 'number'
    case 'select':
      return f.options ? [...f.options, ''].map((o) => JSON.stringify(o)).join(' | ') : 'string'
    default:
      return 'string'
  }
}

function fieldType(f: Field, pageLocales?: string[], indent = '  '): string {
  if (f.type === 'group') return `Array<{\n${f.fields!.map((s) => `${indent}  ${s.key}: ${fieldType(s, pageLocales, indent + '  ')}`).join('\n')}\n${indent}}>`
  const locales = fieldLocales(f, schema.locales, pageLocales)
  const v = valueType(f)
  if (locales[0] === null) return v
  return `{ ${locales.map((l) => `${l}: ${v.includes('|') ? `(${v})` : v}`).join('; ')} }`
}

const obj = (fields: Field[], pageLocales?: string[], indent = '  ') =>
  `{\n${fields.map((f) => `${indent}${f.key}: ${fieldType(f, pageLocales, indent)}`).join('\n')}\n${indent.slice(2)}}`

let out = `/* Generated by scripts/content/gen-types.ts from schema.json — do not edit. */\n\n`
out += `export type Locale = ${schema.locales.map((l: string) => JSON.stringify(l)).join(' | ')}\n\n`
out += `export type Media = { url: string; width?: number | null; height?: number | null; alt?: string; id?: number }\n\n`

const settingsFields = schema.settings.groups.flatMap((g: any) => g.fields)
out += `export type Settings = ${obj(settingsFields)}\n\n`

const pageNames: string[] = []
for (const [slug, t] of Object.entries<any>(schema.pages)) {
  const sections = [...t.sections, ...(t.seo === false ? [] : [{ key: 'seo', fields: schema.pageSeo }])]
  const name = `${pascal(slug)}Page`
  pageNames.push(`  ${JSON.stringify(slug)}: ${name}`)
  out += `export type ${name} = {\n${sections.map((s: any) => `  ${s.key}: ${obj(s.fields, t.locales, '    ')}`).join('\n')}\n}\n\n`
}
out += `export type Pages = {\n${pageNames.join('\n')}\n}\nexport type PageSlug = keyof Pages\n\n`

const itemNames: string[] = []
for (const [type, def] of Object.entries<any>(schema.postTypes)) {
  if (type === 'althea_page') continue
  const name = `${pascal(type.replace(/^althea_/, ''))}Fields`
  itemNames.push(`  ${type}: ${name}`)
  out += `export type ${name} = ${obj(def.fields)}\n\n`
}
out += `export type ItemFields = {\n${itemNames.join('\n')}\n}\nexport type ItemType = keyof ItemFields\n\n`

out += `export type Term = { slug: string; name: string; name_el: string; sort_order: number }\n`
out += `export type TaxonomyOf = {\n${Object.entries<any>(schema.postTypes)
  .filter(([t]) => t !== 'althea_page')
  .map(([t, d]) => `  ${t}: ${(d.taxonomies ?? []).map((x: string) => JSON.stringify(x)).join(' | ') || 'never'}`)
  .join('\n')}\n}\n`
out += `export type Taxonomy = ${Object.keys(schema.taxonomies).map((x) => JSON.stringify(x)).join(' | ')}\n\n`
out += `export type Item<T extends ItemType> = {\n  slug: string\n  title: string\n  excerpt: string\n  menuOrder: number\n  image: Media | null\n  fields: ItemFields[T]\n  terms: { [K in TaxonomyOf[T]]: Term[] }\n}\n`

fs.writeFileSync(OUT, out)
console.log(`Wrote ${path.relative(ROOT, OUT)}`)
